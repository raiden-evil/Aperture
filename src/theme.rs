static THEME: AtomicU8 = AtomicU8::new(0);
pub const NAMES: [&str; 3] = ["Light", "Dark", "Charcoal"];

pub fn set(t: u8) {
    THEME.store(t.min(2), Relaxed);
}
pub fn current() -> u8 {
    THEME.load(Relaxed)
}
pub fn get(t: u8) -> &'static Pal {
    match t {
        1 => &DARK,
        2 => &CHARCOAL,
        _ => &LIGHT,
    }
}
pub fn pal() -> &'static Pal {
    get(current())
}

/// Dark title-bar/border hint for our custom windows (Win11 DWM).
pub unsafe fn apply_window(h: windows_sys::Win32::Foundation::HWND) {
    use windows_sys::Win32::Graphics::Dwm::DwmSetWindowAttribute;
    let dark: i32 = pal().dark as i32;
    DwmSetWindowAttribute(h, 20, &dark as *const i32 as *const _, 4);
    let border: u32 = match current() {
        2 => 0x0030_3030,
        1 => 0x0040_3C38,
        _ => 0xFFFF_FFFF, // DWMWA_COLOR_DEFAULT
    };
    DwmSetWindowAttribute(h, 34, &border as *const u32 as *const _, 4);
}
